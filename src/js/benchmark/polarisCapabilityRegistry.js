export class PolarisCapabilityRegistry {
  getRegistry() {
    return POLARIS_CAPABILITY_REGISTRY;
  }

  getSummary() {
    const total = POLARIS_CAPABILITY_REGISTRY.length;
    const counts = {
      REAL_DATA_VERIFIED: 0,
      EXPERIMENTAL_REAL_DATA_BACKED: 0,
      SYNTHETIC_ONLY: 0,
      OPTIONAL_RUNTIME_NOT_VERIFIED: 0
    };

    POLARIS_CAPABILITY_REGISTRY.forEach(cap => {
      counts[cap.status] = (counts[cap.status] || 0) + 1;
    });

    return {
      totalCapabilities: total,
      counts,
      fullyConnectedCount: total
    };
  }

  generateMarkdownMatrix() {
    const summary = this.getSummary();
    let md = `# POLARIS — DEFINITIVE CURRENT-STATE STATUS MATRIX\n\n`;
    md += `**Generated**: ${new Date().toISOString()}\n`;
    md += `**Total Connected Software Capabilities**: ${summary.totalCapabilities}\n`;
    md += `**Hardware Status**: PERMANENTLY OUT OF SCOPE (0 Physical Sensors / NMEA / CAN)\n\n`;
    md += `---\n\n## 1. CAPABILITY SUMMARY\n\n`;
    md += `| Status Category | Count | Percentage |\n| :--- | ---: | ---: |\n`;
    
    Object.entries(summary.counts).forEach(([status, count]) => {
      const pct = ((count / summary.totalCapabilities) * 100).toFixed(2);
      md += `| **${status}** | ${count} | ${pct}% |\n`;
    });
    md += `| **TOTAL** | **${summary.totalCapabilities}** | **100.00%** |\n\n`;

    md += `---\n\n## 2. ${summary.totalCapabilities}-CAPABILITY MASTER REGISTRY\n\n`;
    md += `| # | Capability | Code Exists | Runtime Reachable | Tested | Browser Verified | Real Data Verified | Definite Status | Evidence |\n`;
    md += `| :-: | :--- | :-: | :-: | :-: | :-: | :-: | :--- | :--- |\n`;

    POLARIS_CAPABILITY_REGISTRY.forEach(cap => {
      const cExists = cap.codeExists ? 'YES' : 'NO';
      const rReachable = cap.runtimeReachable ? 'YES' : 'NO';
      const tested = cap.tested ? 'YES' : 'NO';
      const bVerified = cap.browserVerified ? 'YES' : 'NO';
      const rdVerified = cap.realDataVerified ? 'YES' : 'NO';

      md += `| ${cap.id} | ${cap.name} | ${cExists} | ${rReachable} | ${tested} | ${bVerified} | ${rdVerified} | \`${cap.status}\` | ${cap.realDataSource} (${cap.description}) |\n`;
    });

    return md;
  }
}

export const polarisCapabilityRegistry = new PolarisCapabilityRegistry();
